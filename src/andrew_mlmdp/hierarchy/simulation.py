"""Synthetic trials from a planted hierarchy, for recovery studies.

Trials are generated by the existing rollout engine (``Task.rollout``), so the
generator is exactly the stochastic process that the hierarchy's likelihood
claims to score. A design lists one ``(session_id, start, goal)`` per trial,
which lets a real animal's sessions, starts, goals, and trial counts be copied
directly.

Rollouts that end without reaching the goal are returned separately with their
status rather than silently dropped, so censoring is visible to the caller.
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass
from typing import TYPE_CHECKING

import numpy as np

from andrew_mlmdp.dataset import Trial
from andrew_mlmdp.maze import Coordinate

if TYPE_CHECKING:
    from andrew_mlmdp.hierarchy.model import Template


@dataclass(frozen=True)
class CensoredRollout:
    """A designed trial whose rollout ended before reaching the goal."""

    session_id: str
    trial_id: int
    goal: Coordinate
    start: Coordinate
    status: str
    trajectory: tuple[Coordinate, ...]


@dataclass(frozen=True)
class SimulatedTrials:
    """Completed synthetic trials, censored rollouts, and sampling settings."""

    trials: tuple[Trial, ...]
    censored: tuple[CensoredRollout, ...]
    seed: int
    max_steps: int
    max_abstract_accesses: int


def simulate_trials(
    template: "Template",
    design: Sequence[tuple[str, Coordinate, Coordinate]],
    *,
    seed: int,
    max_steps: int = 500,
    max_abstract_accesses: int = 500,
) -> SimulatedTrials:
    """Roll out one trial per ``(session_id, start, goal)`` design entry.

    Per-trial seeds are spawned from ``seed`` with the same scheme as
    ``sample_rollouts``. ``trial_id`` is the position within its session.
    Only exact goal learning is used.
    """

    entries = tuple(
        (str(session_id), tuple(start), tuple(goal))
        for session_id, start, goal in design
    )
    if not entries:
        raise ValueError("design must contain at least one trial")
    maze = template.maze
    for _, start, goal in entries:
        maze.state_index(start)
        maze.state_index(goal)
        if start == goal:
            raise ValueError(f"Designed start {start} equals its goal")

    children = np.random.SeedSequence(seed).spawn(len(entries))
    trials = []
    censored = []
    next_trial_id: dict[str, int] = {}
    for (session_id, start, goal), child in zip(entries, children, strict=True):
        trial_id = next_trial_id.get(session_id, 0)
        next_trial_id[session_id] = trial_id + 1
        rollout = template.task(goal).rollout(
            start,
            max_steps=max_steps,
            max_abstract_accesses=max_abstract_accesses,
            seed=int(child.generate_state(1, dtype=np.uint64)[0]),
        )
        if rollout.status == "reached_goal":
            trials.append(Trial(session_id, trial_id, goal, rollout.trajectory))
        else:
            censored.append(
                CensoredRollout(
                    session_id=session_id,
                    trial_id=trial_id,
                    goal=goal,
                    start=start,
                    status=rollout.status,
                    trajectory=rollout.trajectory,
                )
            )
    return SimulatedTrials(
        trials=tuple(trials),
        censored=tuple(censored),
        seed=int(seed),
        max_steps=max_steps,
        max_abstract_accesses=max_abstract_accesses,
    )
